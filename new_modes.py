# 7. 🎄 HOLIDAY MODE — ПЬЯНЫЙ НАБОР, ЗВУКИ ЗАСТОЛЬЯ И ПОХМЕЛЬНЫЙ ПРОГНОЗ
# ══════════════════════════════════════════════════════════════════════════════
def transform_holiday(text: str, header: str | None = None) -> tuple[str, str]:
    vowels = "аеиоуыэюяёАЕИОУЫЭЮЯЁ"
    words = text.split()
    for i in range(len(words)):
        if len(words[i]) > 3 and random.random() < 0.35:
            v_idx = [idx for idx, c in enumerate(words[i]) if c in vowels]
            if v_idx:
                ch_idx = random.choice(v_idx)
                words[i] = words[i][:ch_idx] + words[i][ch_idx] * random.randint(2, 4) + words[i][ch_idx+1:]
        if random.random() < 0.20:
            words[i] = words[i].upper()
    drunk_text = " ".join(words)
    
    sounds = [
        "*громко чокается бокалом советского через экран*",
        "*лицом падает в тазик с оливье*",
        "*включает Меладзе на полную громкость*",
        "*кричит в окно: С НОВЫМ ГОДОМ СУКИ!*",
        "*роняет бутылку шампанского на ногу*"
    ]
    
    forecast_chance = random.randint(3, 19)
    
    output = (
        f"🎄 <b>[НОВОГОДНИЙ ПЬЯНЫЙ УГАР]:</b>\n"
        f"«{drunk_text}»\n\n"
        f"🥂 <i>{random.choice(sounds)}</i>\n\n"
        f"🍾 <b>[ПРОГНОЗ НА УТРО 1 ЯНВАРЯ]:</b>\n"
        f"Шанс вспомнить этот пост: <code>{forecast_chance}%</code> | Уровень сухости: <code>Сахара</code> | Рецепт: <code>Банка рассола залпом!</code>"
    )
    return "text", output

