def _replace_words(text: str, profile: ModeProfile) -> str:
    if not profile.pattern or not profile.replacements:
        return text
    def repl(match: re.Match[str]) -> str:
        source = match.group(0)
        if random.random() > profile.replace_chance:
            return source
        value = profile.replacements.get(_key(source))
        if value is None:
            return source
        return _match_case(source, _choose(value))
    return profile.pattern.sub(repl, text)

def _inject(text: str, profile: ModeProfile) -> str:
    words = text.split()
    if len(words) < 5 or random.random() > profile.inject_chance or not profile.injections:
        return text
    max_items = min(profile.max_injections, max(1, len(words) // 8))
    for _ in range(random.randint(1, max_items)):
        idx = random.randint(1, len(words) - 1)
        words.insert(idx, _choose(profile.injections))
    return " ".join(words)

