def transform_abu_mode(text: str, header: str | None = None) -> tuple[str, str]:
    """Главный диспетчер ультра-движка Абу (10 процедурных форматов с глубоким рандомом)."""
    words = text.split()
    dice = random.random()

    # Если сообщение ультра-короткое (1-2 слова), сразу в лоб быстрый формат
    if len(words) <= 2 and random.random() < 0.5:
        if random.random() < 0.5:
            return "text", _format_abu_ticket(text)
        else:
            return "text", _format_thread_mirror(text)

    if dice < 0.30:
        return "text", _format_procedural_bugurt(text)
    elif dice < 0.48:
        return "text", _format_greentext_novel(text)
    elif dice < 0.63:
        return "text", _format_thread_mirror(text)
    elif dice < 0.73:
        return "text", _format_abu_voice_memo(text)
    elif dice < 0.81:
        return "text", _format_psych_dossier(text)
    elif dice < 0.88:
        return "text", _format_abu_ticket(text)
    elif dice < 0.93:
        return "text", _format_server_incident(text)
    elif dice < 0.97:
        return "text", _format_captcha_disaster(text)
    else:
        return "text", _format_board_catalog(text)
