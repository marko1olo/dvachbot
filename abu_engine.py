def _format_procedural_bugurt(text: str) -> str:
    board = random.choice(_ABU_BOARDS)
    age = random.randint(18, 33)

    intro = random.choice(_ABU_BUGURT_INTROS).format(board=board, age=age)

    sentences = [s.strip() for s in re.split(r'[.!?\n]+', text) if s.strip()]
    middle = []
    for s in sentences[:4]:
        mutated = _mutate_text(s)
        clean = mutated.strip().upper()
        clean = re.sub(r'[.!?]+$', '', clean)
        if clean:
            if random.random() < 0.35:
                tag = random.choice(['(ДВАЧУЮ БАЗУ)', '(САЖА СКРЫЛ)', '(ОП-ХУЙ ДЕТЕКТЕД)', '(ШИЗА ПРОГРЕССИРУЕТ)', '(БАТЯ УЖЕ ГРЕМИТ РЕМНЕМ)'])
                clean += f" @ {tag}"
            middle.append(clean)

    if not middle:
        middle = ["ВЫДАЕШЬ ГЕНИАЛЬНУЮ МЫСЛЬ В ТРЕД", "ЖДЕШЬ ЧТО ВЕСЬ /b/ ПРИЗНАЕТ ТЕБЯ ГИГАЧАДОМ"]

    middle_str = "\n@\n".join(middle)
    escalation = random.choice(_ABU_BUGURT_ESCALATIONS).format(board=board)
    final = random.choice(_ABU_BUGURT_FINALS)

    bugurt_body = f"{intro}\n@\n{middle_str}\n@\n{escalation}\n@\n{final}"

