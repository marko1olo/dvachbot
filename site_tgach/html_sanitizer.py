"""
Единственная реализация веб-версии sanitize_html для site_tgach и Dubsite_tgach.

Зачем отдельный модуль: функция была скопирована в site_tgach/main.py и в
Dubsite_tgach/main.py, и копии разошлись — в дубле не экранировался '&', а None
превращался в строку "None". Тот же класс расхождения уже стоил живого TypeError в
get_cached_file_path: параметр allow_protected_tokens завели в site_tgach и не
перенесли в дубль, вызов падал с "unexpected keyword argument" (комментарий на
Dubsite_tgach/main.py:6280 описывает ровно этот случай). Пока реализация одна,
следующая правка стоит одного места, а не двух.

Почему не common/text_utils.sanitize_html: та функция решает другую задачу — белый
список тегов Telegram HTML (<b>, <a href="https://...">), её вывод уходит в
message.answer(parse_mode="HTML"). Для веба белый список тегов опасен: он пропустил
бы присланный пользователем <a href> прямо в HTML страницы. Веб-версия обязана
экранировать всё; разметку обратно вносит format_post_text уже на выводе.

Правильный конечный адрес этого файла — common/, рядом с text_utils.py, отдельной
функцией и без слияния с телеграмным белым списком. Модуль намеренно оставлен
пустым от зависимостей (только stdlib html), чтобы такой перенос был механическим.
"""

import html


def sanitize_html(text) -> str:
    """
    Экранирует текст пользователя перед сохранением поста.

    quote=False сохранено из site_tgach дословно: живой сайт уже хранит тексты,
    прошедшие через этот вызов, а на выводе format_post_text экранирует ещё раз с
    quote=True, поэтому в HTML-атрибут сырая кавычка не попадает. Переключение на
    quote=True изменило бы вид уже сохранённых постов (двойное экранирование стало
    бы видимым как &amp;quot;), поэтому это не косметика, а поведение.

    Нестроковый вход приводится к строке И экранируется. Копия из Dubsite отдавала
    str(text) без экранирования, то есть объект с '<script>' в __str__ проходил
    насквозь; site_tgach на том же входе падал с AttributeError внутри html.escape.
    Пустое/None даёт "" — дубль на None возвращал строку "None", и она попадала бы
    в текст поста.
    """
    if not text:
        return ""
    if not isinstance(text, str):
        text = str(text)
    return html.escape(text, quote=False)
