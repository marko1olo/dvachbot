def transform_rus_mode(text: str, header: str | None = None) -> tuple[str, str]:
    """
    Трансформация текста в режиме «Русы против Ящеров» v5.5.
    10 процедурных сценариев с максимальной аутентичностью и безумием.
    """
    morphed_text = _rus_morph_text(text)
    lower_orig = text.lower()

    is_whining = any(w in lower_orig for w in _RUS_WHINE_TRIGGERS)

    combat_move = random.choice(_RUS_COMBAT_MOVES)
    rune = random.choice(_RUS_SLAVIC_RUNES)
    baikal_purity = random.randint(91, 100)

    if is_whining:
        output = generate_whining_rebuke(morphed_text, combat_move, baikal_purity)
        return "text", output

    dice = random.random()

    if dice < 0.14:
        output = generate_bagirov_lecture(morphed_text, combat_move, baikal_purity)
    elif dice < 0.27:
        output = generate_drocheslav_raid(morphed_text, combat_move)
    elif dice < 0.39:
        output = generate_lizard_wiretap(morphed_text, combat_move)
    elif dice < 0.51:
        output = generate_slavic_court(morphed_text, rune)
    elif dice < 0.62:
        output = generate_dna_lizard_test(morphed_text, baikal_purity)
    elif dice < 0.73:
        output = generate_slavic_bugurt(morphed_text)
    elif dice < 0.83:
        output = generate_volkhv_remedy(morphed_text, combat_move)
    elif dice < 0.92:
        output = generate_interrogation_protocol(morphed_text, combat_move, baikal_purity)
    else:
        output = generate_combat_dispatch(morphed_text, combat_move)

    return "text", output


rus_transform = transform_rus_mode
