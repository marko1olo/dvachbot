def _rus_morph_text(text: str) -> str:
    """Глубокая замена слов на древнерусский былинный сленг."""
    res = text
    sorted_keys = sorted(_RUS_REPLACEMENTS.keys(), key=len, reverse=True)
    for key in sorted_keys:
        pattern = r'\b' + re.escape(key) + r'\b'
        res = re.sub(pattern, lambda m: random.choice(_RUS_REPLACEMENTS[key]), res, flags=re.IGNORECASE)
    return res


