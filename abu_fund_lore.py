def get_yacht_tier(current_fund: int) -> YachtTier:
    for tier in reversed(YACHT_TIERS):
        if current_fund >= tier.min_amount:
            return tier
    return YACHT_TIERS[0]

def render_progress_bar(current: int, target: int = DEFAULT_YACHT_TARGET, length: int = 14) -> str:
    if target <= 0:
        pct = 1.0
    else:
        pct = max(0.0, min(1.0, current / target))
    filled = int(round(length * pct))
    unfilled = length - filled
    bar = "█" * filled + "░" * unfilled
    return f"[{bar}] {pct * 100:.2f}%"

def format_abu_fund_dashboard(
    current_fund: int,
    target_fund: int = DEFAULT_YACHT_TARGET,
    recent_donors: Optional[List[Tuple[str, int]]] = None
) -> str:
    tier = get_yacht_tier(current_fund)
    progress_bar = render_progress_bar(current_fund, target_fund, length=12)
    pct = (current_fund / target_fund * 100) if target_fund > 0 else 100.0

    features_str = "\n".join(f"  ├ {f}" for f in tier.features[:-1])
    features_str += f"\n  └ {tier.features[-1]}"

    next_tier_info = ""
    for t in YACHT_TIERS:
        if t.min_amount > current_fund:
            diff = t.min_amount - current_fund
            next_tier_info = f"\n🎯 <i>До апгрейда до «{t.name}»:</i> <b>{diff:,} ₪</b>\n"
            break

    donors_section = ""
    if recent_donors:
        donors_section = "\n<b>🩸 Свежие жертвы раскулачивания:</b>\n"
        for name, amt in recent_donors[:4]:
            donors_section += f"  • <b>{name}</b> внес(ла) <code>-{amt:,} ₪</code>\n"

    card = (
        f"🛥️ <b>ОФШОРНЫЙ ФОНД ЯХТЫ АБУ (ЦЕЛЬ: 1 МИЛЛИАРД ₪)</b> 🛥️\n"
        f"<i>«Постинг бесплатный, но яхта и космическая станция сами себя не купят»</i>\n\n"
        f"📊 <b>Прогресс сбора:</b> <code>{progress_bar}</code>\n"
        f"💰 <b>В казне:</b> <code>{current_fund:,} ₪</code> / <code>{target_fund:,} ₪</code> ({pct:.2f}%)\n"
        f"{next_tier_info}\n"
        f"{tier.status_icon} <b>Текущий ранг:</b> <u>{tier.name}</u> (Тир {tier.tier_id})\n"
        f"📝 <b>Статус:</b> <i>{tier.headline}</i>\n"
        f"{tier.description}\n\n"
        f"🛠️ <b>Установленное оборудование:</b>\n"
        f"{features_str}\n\n"
        f"💬 <b>Слово Падишаха:</b>\n"
        f"<i>{tier.abu_speech}</i>\n"
        f"{donors_section}\n"
        f"⚖️ <i>Казна пополняется налогами на сверхприбыль, заносы и рейдом казино.</i>"
    )
    return card

def generate_tax_notification(
    username: str,
    tax_amount: int,
    old_balance: int,
    new_balance: int,
    category: Optional[TaxReasonCategory] = None,
    template_id: Optional[str] = None
) -> str:
    templates = TAX_NOTIFICATION_TEMPLATES
    if template_id:
        matched = [t for t in templates if t["id"] == template_id]
        chosen = matched[0] if matched else random.choice(templates)
    elif category:
        filtered = [t for t in templates if t["category"] == category.value]
        chosen = random.choice(filtered) if filtered else random.choice(templates)
    else:
        chosen = random.choice(templates)

    confiscated_pct = (tax_amount / old_balance * 100) if old_balance > 0 else 0.0

    msg = (
        f"{chosen['title']}\n"
        f"━━━━━━━━━━━━━━━━━━━━━━\n"
        f"👤 <b>Гражданин:</b> {username}\n"
        f"💸 <b>Изъято в казну:</b> <code>-{tax_amount:,} ₪</code> (<b>{confiscated_pct:.1f}%</b>)\n"
        f"💳 <b>Остаток на балансе:</b> <code>{new_balance:,} ₪</code>\n"
        f"🏷️ <b>Статья изъятия:</b> <i>{chosen['tax_type']}</i>\n\n"
        f"🔍 <b>Основание:</b>\n"
        f"<i>{chosen['reason']}</i>\n\n"
        f"💬 <b>Цитата уполномоченного:</b>\n"
        f"<i>{chosen['quote']}</i>\n"
        f"━━━━━━━━━━━━━━━━━━━━━━\n"
        f"🛥️ <i>Средства направлены в Офшорный Фонд Яхты Абу (/abu_fund).</i>"
    )
    return msg

def check_milestone_events(old_fund: int, new_fund: int) -> List[GlobalMilestoneEvent]:
    triggered: List[GlobalMilestoneEvent] = []
    for event in GLOBAL_EVENTS:
        if old_fund < event.threshold <= new_fund:
            triggered.append(event)
    return triggered

